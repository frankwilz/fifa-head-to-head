source("R/metadata.R")
m <- data.frame(match_id="m1",tournament_id="event",tier=NA_character_,platform=NA_character_,source_url="https://example.org/match")
p <- data.frame(player_id=c("p1","p2"),country=c(NA,"GB"),source_url="https://example.org/player")
t <- data.frame(tournament_id="event",tier="world",tier_source_url="https://example.org/results",platform="PS5",platform_source_url="https://example.org/rules",tier_scheme="research_event_scope_v1")
a <- data.frame(player_id=c("p1","p2"),country=c("DK","DE"),source_url="https://example.org/profile",as_of="2026-11-06")
x <- enrich_metadata(m,p,t,a)
stopifnot(x$matches$tier=="world",x$matches$platform=="PS5",x$players$country[1]=="DK",x$players$country[2]=="GB",nrow(x$issues)==1)
fails <- function(expr) inherits(tryCatch(force(expr),error=function(e)e),"error")
bad <- t;bad$platform_source_url <- NA;stopifnot(fails(enrich_metadata(m,p,bad,a)))
bad <- m;bad$platform <- "Xbox";stopifnot(fails(enrich_metadata(bad,p,t,a)))
stopifnot(fails(enrich_metadata(m,p,rbind(t,t),a)),fails(enrich_metadata(m,p,t,rbind(a,a))))
cat("Metadata provenance tests passed.\n")
bad <- a;bad$as_of[1] <- "2026-02-30";stopifnot(fails(enrich_metadata(m,p,t,bad)))
bad <- a;bad$as_of[1] <- "2026-11-07"
x <- enrich_metadata(m,p,t,bad,as.Date("2026-11-06"));stopifnot(is.na(x$players$country[1]))
bad <- t;bad$tier_scheme <- NA;stopifnot(fails(enrich_metadata(m,p,bad,a)))
bad <- a;bad$player_id[1] <- " ";stopifnot(fails(enrich_metadata(m,p,t,bad)))
old <- p;old$country_source_url <- "https://example.org/original-country"
x <- enrich_metadata(m,old,t,a);stopifnot(x$players$country_source_url[2]==old$country_source_url[2])

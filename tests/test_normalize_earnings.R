source("R/normalize_earnings.R")
tmp <- tempfile("earnings-normalization-");dir.create(tmp)
career <- file.path(tmp,"career.json"); edition <- file.path(tmp,"edition.json")
writeLines('{"CurrentHandle":"Known","TotalUSDPrize":"1200.50"}',career)
writeLines('[{"PlayerId":101,"TotalUSDPrize":900},{"PlayerId":999,"TotalUSDPrize":200}]',edition)
m <- data.frame(cache_file=c(career,edition),method=c("LookupPlayerById","LookupHighestEarningPlayersByGame"),
 provider_player_id=c("101",NA),provider_game_id=c(NA,"500"),as_of="2026-11-06",
 source_url=c("https://www.esportsearnings.com/players/101","https://www.esportsearnings.com/games/500"))
p <- data.frame(provider_player_id="101",player_id="player_known")
g <- data.frame(provider_game_id="500",game_edition="FC24")
x <- normalize_earnings_caches(m,p,g)
stopifnot(nrow(x$earnings)==2,nrow(x$rejected)==1,
 x$earnings$earnings_usd[x$earnings$scope=="career"]==1200.5,
 x$earnings$game_edition[x$earnings$scope=="edition"]=="FC24")
fails <- function(expr) inherits(tryCatch(force(expr),error=function(e)e),"error")
stopifnot(fails(normalize_earnings_caches(rbind(m,m[1,]),p,g)))
bad <- m; bad$as_of[1] <- "2026-02-31";stopifnot(fails(normalize_earnings_caches(bad,p,g)))
bad <- m; bad$source_url[1] <- "https://www.esportsearnings.com/?apikey=secret";stopifnot(fails(normalize_earnings_caches(bad,p,g)))
stopifnot(fails(normalize_earnings_caches(m,rbind(p,p),g)),fails(normalize_earnings_caches(m,p,NULL)))
writeLines('{"TotalUSDPrize":-5}',career);stopifnot(fails(normalize_earnings_caches(m,p,g)))
writeLines('{"ErrorCode":1010}',career);stopifnot(fails(normalize_earnings_caches(m,p,g)))
writeLines('{"CurrentHandle":"Known","TotalUSDPrize":"1200.50"}',career)
stopifnot(nrow(normalize_earnings_caches(m[FALSE,],p,g)$earnings)==0)
badp <- p;badp$provider_player_id <- " ";stopifnot(fails(normalize_earnings_caches(m,badp,g)))
badp <- p;badp$player_id <- " ";stopifnot(fails(normalize_earnings_caches(m,badp,g)))
bad <- m;bad$provider_player_id[1] <- "0";stopifnot(fails(normalize_earnings_caches(bad,p,g)))
bad <- m;bad$source_url[1] <- "https://www.esportsearnings.com/players/102";stopifnot(fails(normalize_earnings_caches(bad,p,g)))
bad <- m;bad$source_url[2] <- "https://www.esportsearnings.com/games/501";stopifnot(fails(normalize_earnings_caches(bad,p,g)))
bad <- m;bad$source_url[1] <- "https://www.esportsearnings.com/players/101?api%6Bey=secret";stopifnot(fails(normalize_earnings_caches(bad,p,g)))
bad <- m;bad$as_of[1] <- NA;stopifnot(fails(normalize_earnings_caches(bad,p,g)))
for (amount in c('null','true','[]','[1]','"Inf"','[1,2]')) {
  writeLines(paste0('{"TotalUSDPrize":',amount,'}'),career)
  stopifnot(fails(normalize_earnings_caches(m,p,g)))
}
writeLines('{"TotalUSDPrize":0}',career)
stopifnot(normalize_earnings_caches(m,p,g)$earnings$earnings_usd[1]==0)
writeLines('[{"PlayerId":999,"TotalUSDPrize":"Inf"}]',edition)
stopifnot(fails(normalize_earnings_caches(m,p,g)))
writeLines('[{"PlayerId":[101],"TotalUSDPrize":50}]',edition)
stopifnot(fails(normalize_earnings_caches(m,p,g)))
writeLines('[]',edition);stopifnot(nrow(normalize_earnings_caches(m,p,g)$earnings)==1)
writeLines('{}',edition);stopifnot(fails(normalize_earnings_caches(m,p,g)))
writeLines('[]',edition)
jsonlite::write_json(list(method="LookupPlayerById",params=list(playerid="102"),retrieved_at_utc="2026-11-06 12:00:00 UTC"),
 paste0(career,".metadata.json"),auto_unbox=TRUE)
stopifnot(fails(normalize_earnings_caches(m,p,g)))
jsonlite::write_json(list(method="LookupPlayerById",params=list(playerid="101"),retrieved_at_utc="2026-11-06 12:00:00 UTC"),
 paste0(career,".metadata.json"),auto_unbox=TRUE)
stopifnot(nrow(normalize_earnings_caches(m,p,g)$earnings)==1)
bad <- m;bad$as_of[1] <- "2026-11-05";stopifnot(fails(normalize_earnings_caches(bad,p,g)))
unlink(tmp,recursive=TRUE)
cat("Earnings normalization tests passed.\n")
